// Regenerates src/mcp/series-chart/view-bundle.generated.ts: the client script (view.ts + the view-entry.ts
// protocol client) bundled as one classic IIFE, so the served HTML needs no <script src> and no module scripts.
// Run: npm run build:mcp-view   (tests/hl-030a.view-bundle-fresh.test.ts fails if the committed file is stale.)
// esbuild API: https://esbuild.github.io/api/#build  (esbuild is already in the tree via vite/tsx).
import { buildSync } from "esbuild";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export function bundleView(): string {
  const out = buildSync({
    entryPoints: [`${root}src/mcp/series-chart/view-entry.ts`],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    define: { "process.env.NODE_ENV": '"production"' },
  });
  // "</script" inside a string literal would end the inline script early.
  return out.outputFiles[0]!.text.replace(/<\/(script)/gi, "<\\/$1");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const js = bundleView();
  const header = "// GENERATED by scripts/build-mcp-view.ts (npm run build:mcp-view). Do not edit.\n";
  writeFileSync(`${root}src/mcp/series-chart/view-bundle.generated.ts`, `${header}export const VIEW_SCRIPT: string = ${JSON.stringify(js)};\n`);
  console.log(`view bundle: ${js.length} bytes`);
}
